"""Study 1 & 2: teacher-forced probe of how a failure record changes the
probability of re-emitting the failed action.

A *probe item* freezes one decision point of an agent trajectory: the context
up to step t (built by executing the reference actions for real), a plausible
wrong action `a_fail` that would fail at step t, the observation the runtime
would return for it, and the correct action `a_gold`. Because the wrong action
is generated by a fixed perturbation operator rather than sampled from a model,
every model in the ladder sees exactly the same items — the scaling curve
therefore cannot be an artefact of easier items for bigger models.

A *condition* is a way of writing that failure into the context (or not writing
it at all). Scoring one fixed candidate string under several conditions gives
the differences the paper is about.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple

from .harness import (
    NEGATIVE_INSTRUCTION,
    TrajStep,
    abstract_failure,
)

# --------------------------------------------------------------------------
# Items
# --------------------------------------------------------------------------


@dataclass
class ProbeItem:
    item_id: str
    env: str
    task_id: str
    template: str
    step_index: int
    operator: str
    error_type: str
    system_prompt: str
    goal: str
    prefix_actions: List[str]
    prefix_observations: List[str]
    failed_action: str
    gold_action: str
    #: Observations for the same failed action under different renderings.
    obs_fail: str
    obs_fail_terse: str
    obs_fail_verbose: str
    obs_fail_echo: str
    obs_success: str
    obs_neutral: str
    #: Error text for the distractor used by the `fail_other` placebo.
    obs_fail_other: str = ""
    distractors: List[str] = field(default_factory=list)
    tool: Optional[str] = None
    #: Environment-specific extras kept for the analysis (e.g. whether the
    #: interpreter's own traceback happened to quote a line of the submission).
    meta: Dict[str, Any] = field(default_factory=dict)

    def prefix_steps(self) -> List[TrajStep]:
        return [
            TrajStep(action=a, observation=o, ok=True)
            for a, o in zip(self.prefix_actions, self.prefix_observations)
        ]

    def failed_step(self, observation: Optional[str] = None) -> TrajStep:
        return TrajStep(
            action=self.failed_action,
            observation=observation if observation is not None else self.obs_fail,
            ok=False,
            error_type=self.error_type,
            tool=self.tool,
        )


