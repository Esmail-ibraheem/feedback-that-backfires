def build_toolshed_items(
    n_tasks: int = 90,
    seed: int = 20260808,
    max_per_operator: int = 80,
    n_distractors: int = 2,
) -> List[ProbeItem]:
    """Build a balanced probe set from ToolShed.

    Balancing is over *perturbation operator* (which determines the error
    family). Without it the set would be dominated by `tool_typo` and
    `arg_typo`, which apply to every call.
    """
    from .envs.toolshed import ToolShedEnv, parse_action
    from .envs.toolshed_tasks import generate_tasks, perturbations

    # The *primary* rendering does not quote the failed call back to the model,
    # so that the `fail` / `succ` / `neut` contexts contain the action string
    # exactly once each (as the assistant turn). Quoting is studied separately
    # as the `fail_echo` condition, where it is the only thing that changes.
    env_std = ToolShedEnv(verbosity="standard", echo_action=False)
    env_terse = ToolShedEnv(verbosity="terse", echo_action=False)
    env_verbose = ToolShedEnv(verbosity="verbose", echo_action=False)
    env_echo = ToolShedEnv(verbosity="standard", echo_action=True)

    tasks = generate_tasks(n_tasks, seed=seed)
    by_operator: Dict[str, List[ProbeItem]] = {}

    for task in tasks:
        for env in (env_std, env_terse, env_verbose, env_echo):
            env.reset(task)
        system_prompt = env_std.system_prompt(task)
        prefix_actions: List[str] = []
        prefix_observations: List[str] = []

        for step_index, gold in enumerate(task.gold_actions):
            if gold.strip() == "finish()":
                break
            world = env_std.world(task)
            perts = perturbations(gold, world)
            # Distractors: other perturbations of the same gold action. Scoring
            # them lets us report a properly normalised P(repeat) rather than
            # an unnormalised log-probability difference.
            for pert_index, pert in enumerate(perts):
                others = [p.action for p in perts if p.action != pert.action]
                distractors = others[:n_distractors]

                out_other = (
                    env_std.step(task, distractors[0]) if distractors else None
                )
                out_std = env_std.step(task, pert.action)
                out_terse = env_terse.step(task, pert.action)
                out_verbose = env_verbose.step(task, pert.action)
                out_echo = env_echo.step(task, pert.action)
                # A perturbation that unexpectedly succeeds is not usable.
                if out_std.ok:
                    continue
                # Failed calls must not mutate the world; assert by re-checking.
                assert out_std.error_type is not None

                try:
                    tool = parse_action(pert.action).name
                except Exception:  # noqa: BLE001
                    tool = None

                item = ProbeItem(
                    # `pert_index` disambiguates two perturbations that share an
                    # operator name for the same call (e.g. two different malformed
                    # dates). Without it their scores would collide in the analysis.
                    item_id=f"{task.task_id}-s{step_index}-{pert.operator}-{pert_index}",
                    env="toolshed",
                    task_id=task.task_id,
                    template=task.payload["template"],
                    step_index=step_index,
                    operator=pert.operator,
                    error_type=out_std.error_type or "unknown",
                    system_prompt=system_prompt,
                    goal=task.goal,
                    prefix_actions=list(prefix_actions),
                    prefix_observations=list(prefix_observations),
                    failed_action=pert.action,
                    gold_action=gold,
                    obs_fail=out_std.observation,
                    obs_fail_terse=out_terse.observation,
                    obs_fail_verbose=out_verbose.observation,
                    obs_fail_echo=out_echo.observation,
                    obs_success=env_std.success_observation(pert.action, out_std),
                    obs_neutral=env_std.neutral_observation(pert.action, out_std),
                    obs_fail_other=(
                        out_other.observation
                        if out_other is not None and not out_other.ok
                        else ""
                    ),
                    distractors=distractors,
                    tool=tool,
                )
                by_operator.setdefault(pert.operator, []).append(item)

            # Advance the real trajectory with the reference action.
            obs = env_std.step(task, gold)
            assert obs.ok, f"reference action failed: {gold} -> {obs.observation}"
            for env in (env_terse, env_verbose, env_echo):
                env.step(task, gold)
            prefix_actions.append(gold)
            prefix_observations.append(obs.observation)

    items: List[ProbeItem] = []
    for operator in sorted(by_operator):
        items.extend(by_operator[operator][:max_per_operator])
    items.sort(key=lambda it: it.item_id)
    return items


