#: (name, description) for every context we score under.
CONDITION_DOC: Dict[str, str] = {
    "pre": "context before the attempt (baseline)",
    "fail": "attempt + error observation (standard ReAct harness)",
    "succ": "attempt + counterfactual success observation",
    "neut": "attempt + valence-free observation",
    "neut_pad": "attempt + valence-free observation, length-matched to `fail`",
    "abstract": "harness-generated failure description, no verbatim call",
    "fail_echo": "as `fail`, but the error quotes the failed call verbatim",
    "fail_terse": "as `fail`, with the shortest error rendering",
    "fail_verbose": "as `fail`, with the longest error rendering",
    "fail_instr": "as `fail`, plus an explicit do-not-repeat instruction",
    "fail_k2": "the same call fails twice",
    "fail_k3": "the same call fails three times",
    "fail_early": "as `fail`, but the failure precedes the successful steps",
    "fail_other": "a DIFFERENT wrong action failed; the scored one was never written",
    "abstract_min": "bare failure marker, no diagnosis and no verbatim call",
}

CORE_CONDITIONS = ["pre", "fail", "succ", "neut", "abstract"]
EXTENDED_CONDITIONS = [
    "neut_pad",
    "fail_echo",
    "fail_terse",
    "fail_verbose",
    "fail_instr",
    "fail_k2",
    "fail_k3",
    "fail_early",
    "fail_other",
    "abstract_min",
]


def config_free_observation_role(_prefix: str) -> str:
    """Observations always come back as a user turn (see HarnessConfig)."""
    return "user"


def build_condition_messages(
    item: ProbeItem,
    condition: str,
    neutral_obs_padded: Optional[str] = None,
    observation_prefix: str = "Observation: ",
) -> List[Dict[str, str]]:
    """Render the chat messages for one probe condition.

    The only thing that differs between conditions is the failure record; the
    system prompt, the goal and the successful prefix steps are byte-identical.
    """
    system = item.system_prompt
    if condition == "fail_instr":
        system = f"{system}\n{NEGATIVE_INSTRUCTION}"

    msgs: List[Dict[str, str]] = [
        {"role": "system", "content": system},
        {"role": "user", "content": item.goal},
    ]

    def push_ok_steps() -> None:
        for a, o in zip(item.prefix_actions, item.prefix_observations):
            msgs.append({"role": "assistant", "content": a})
            msgs.append({"role": "user", "content": f"{observation_prefix}{o}"})

    def push_failure(obs: str, repeats: int = 1) -> None:
        for _ in range(repeats):
            msgs.append({"role": "assistant", "content": item.failed_action})
            msgs.append({"role": "user", "content": f"{observation_prefix}{obs}"})

    if condition == "fail_early":
        push_failure(item.obs_fail)
        push_ok_steps()
        return msgs

    push_ok_steps()

    if condition == "pre":
        pass
    elif condition == "fail":
        push_failure(item.obs_fail)
    elif condition == "succ":
        push_failure(item.obs_success)
    elif condition == "neut":
        push_failure(item.obs_neutral)
    elif condition == "neut_pad":
        if neutral_obs_padded is None:
            raise ValueError("neut_pad requires a length-matched observation")
        push_failure(neutral_obs_padded)
    elif condition == "abstract":
        msgs.append(
            {"role": "user", "content": abstract_failure(item.failed_step(), 1)}
        )
    elif condition == "abstract_min":
        # Removes the surface form *and* the diagnosis. Isolates how much of the
        # abstraction's benefit comes from the wording we chose for the gloss
        # versus from the mere absence of the failed call.
        msgs.append({"role": "user", "content": "[attempt 1 failed]"})
    elif condition == "fail_other":
        # Placebo: a different plausible-but-wrong call is recorded as having
        # failed. The action we score was never written into the context, so any
        # rise in its probability cannot be surface-form copying of *it*. This
        # separates "a failure happened" from "this string is in the context".
        if not item.distractors:
            raise ValueError("fail_other requires a distractor action")
        other = item.distractors[0]
        msgs.append({"role": "assistant", "content": other})
        msgs.append(
            {
                "role": config_free_observation_role(observation_prefix),
                "content": f"{observation_prefix}{item.obs_fail_other or item.obs_fail}",
            }
        )
    elif condition == "fail_echo":
        push_failure(item.obs_fail_echo)
    elif condition == "fail_terse":
        push_failure(item.obs_fail_terse)
    elif condition == "fail_verbose":
        push_failure(item.obs_fail_verbose)
    elif condition == "fail_instr":
        push_failure(item.obs_fail)
    elif condition == "fail_k2":
        push_failure(item.obs_fail, repeats=2)
    elif condition == "fail_k3":
        push_failure(item.obs_fail, repeats=3)
    else:
        raise KeyError(f"unknown condition {condition!r}")
    return msgs


