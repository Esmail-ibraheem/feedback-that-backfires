def build_coderepair_items(
    n_problems: int = 120,
    seed: int = 20260808,
    max_per_operator: int = 70,
    n_distractors: int = 2,
    data_dir: str = "data/mbpp",
    timeout: float = 10.0,
) -> List[ProbeItem]:
    """Build probe items from MBPP by mutating reference solutions.

    A mutation is kept only if (a) the reference solution passes and (b) the
    mutant actually fails — so every item is a genuine failure with a genuine
    interpreter message, and the "wrong" program is one single edit away from a
    correct one.
    """
    from .envs.coderepair import (
        SYSTEM_PROMPT,
        load_mbpp,
        mutate,
        neutral_observation,
        render_observation,
        run_program,
        success_observation,
    )

    problems = load_mbpp(data_dir)[:n_problems]
    by_operator: Dict[str, List[ProbeItem]] = {}

    for p in problems:
        tests = p["test_list"]
        ref = run_program(p["code"], tests, timeout=timeout)
        if not ref.ok:
            continue  # a handful of MBPP references do not pass their own tests
        muts = mutate(p["code"])
        results = []
        for m in muts:
            r = run_program(m.code, tests, timeout=timeout)
            if not r.ok:
                results.append((m, r))
        if not results:
            continue
        goal = f"{p['prompt']}\n\nThe tests are:\n" + "\n".join(tests)
        for m, r in results:
            others = [(o, rr) for o, rr in results if o.code != m.code]
            distractors = [o.code for o, _ in others][:n_distractors]
            obs_other = (
                render_observation(others[0][1], len(tests), "standard", False,
                                   others[0][0].code)
                if others
                else ""
            )
            obs_fail = render_observation(r, len(tests), "standard", False, m.code)
            quotes = any(
                len(ln.strip()) > 8 and ln.strip() in obs_fail
                for ln in m.code.splitlines()
            )
            item = ProbeItem(
                item_id=f"mbpp-{p['task_id']:04d}-{m.operator}-{results.index((m, r))}",
                env="coderepair",
                task_id=f"mbpp-{p['task_id']:04d}",
                template="mbpp",
                step_index=0,
                operator=m.operator,
                error_type=r.kind,
                system_prompt=SYSTEM_PROMPT,
                goal=goal,
                prefix_actions=[],
                prefix_observations=[],
                failed_action=m.code,
                gold_action=p["code"].strip(),
                obs_fail=obs_fail,
                obs_fail_terse=render_observation(r, len(tests), "terse", False, m.code),
                obs_fail_verbose=render_observation(
                    r, len(tests), "verbose", False, m.code
                ),
                obs_fail_echo=render_observation(
                    r, len(tests), "standard", True, m.code
                ),
                obs_success=success_observation(len(tests)),
                obs_neutral=neutral_observation(len(tests)),
                obs_fail_other=obs_other,
                distractors=distractors,
                tool=None,
                meta={
                    "traceback_quotes_source": bool(quotes),
                    "tests_passed_before_failure": r.passed,
                    "n_tests": len(tests),
                },
            )
            by_operator.setdefault(m.operator, []).append(item)

    items: List[ProbeItem] = []
    for operator in sorted(by_operator):
        items.extend(by_operator[operator][:max_per_operator])
    items.sort(key=lambda it: it.item_id)
    return items


def stratified_subsample(
    items: Sequence[ProbeItem],
    n: int,
    seed: int = 20260808,
    max_per_task: Optional[int] = None,
) -> List[ProbeItem]:
    """Deterministically thin an item set while keeping operator balance.

    CPU inference is the binding constraint in this project, so item sets are
    built large and then thinned. Thinning round-robin over operators (rather
    than taking a prefix) keeps every error family represented; capping items
    per task raises the number of independent bootstrap clusters, which is what
    the confidence intervals actually depend on.
    """
    import random as _random

    rng = _random.Random(seed)
    by_op: Dict[str, List[ProbeItem]] = {}
    for it in items:
        by_op.setdefault(it.operator, []).append(it)
    for op in by_op:
        by_op[op] = sorted(by_op[op], key=lambda i: i.item_id)
        rng.shuffle(by_op[op])

    per_task: Dict[str, int] = {}
    chosen: List[ProbeItem] = []
    ops = sorted(by_op)
    cursor = {op: 0 for op in ops}
    while len(chosen) < n and any(cursor[op] < len(by_op[op]) for op in ops):
        for op in ops:
            if len(chosen) >= n:
                break
            while cursor[op] < len(by_op[op]):
                cand = by_op[op][cursor[op]]
                cursor[op] += 1
                if max_per_task and per_task.get(cand.task_id, 0) >= max_per_task:
                    continue
                per_task[cand.task_id] = per_task.get(cand.task_id, 0) + 1
                chosen.append(cand)
                break
    chosen.sort(key=lambda i: i.item_id)
    return chosen


def save_items(items: Sequence[ProbeItem], path: str) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        for it in items:
            fh.write(json.dumps(asdict(it), ensure_ascii=False) + "\n")


def load_items(path: str) -> List[ProbeItem]:
    out: List[ProbeItem] = []
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            if line.strip():
                out.append(ProbeItem(**json.loads(line)))
    return out
